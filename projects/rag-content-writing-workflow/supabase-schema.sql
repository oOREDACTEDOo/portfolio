-- ============================================================
-- HELPER FUNCTION: Vector similarity search for RAG
-- Call this from n8n to retrieve relevant chunks for a client.
-- ============================================================
create or replace function match_content_chunks(
  query_embedding vector(1536),
  match_client_id uuid,
  match_threshold float default 0.7,
  match_count int default 10
)
returns table (
  id uuid,
  chunk_text text,
  context_prefix text,
  source_article_title text,
  source_url text,
  topic_tags text[],
  keyword_tags text[],
  content_type_tag text,
  intent_tag text,
  asset_tags text[],
  funnel_stage text,
  similarity float
)
language sql stable
as $$
  select
    cc.id,
    cc.chunk_text,
    cc.context_prefix,
    cc.source_article_title,
    cc.source_url,
    cc.topic_tags,
    cc.keyword_tags,
    cc.content_type_tag,
    cc.intent_tag,
    cc.asset_tags,
    cc.funnel_stage,
    1 - (cc.embedding <=> query_embedding) as similarity
  from content_chunks cc
  where cc.client_id = match_client_id
    and 1 - (cc.embedding <=> query_embedding) > match_threshold
  order by cc.embedding <=> query_embedding
  limit match_count;
$$;

-- ============================================================
-- UPDATED_AT TRIGGER
-- Automatically update the updated_at column on row changes.
-- ============================================================
create or replace function update_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger trg_clients_updated_at
  before update on clients
  for each row execute function update_updated_at();

create trigger trg_voice_profiles_updated_at
  before update on voice_profiles
  for each row execute function update_updated_at();

create trigger trg_content_types_updated_at
  before update on content_types
  for each row execute function update_updated_at();
